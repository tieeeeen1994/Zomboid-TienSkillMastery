"""Builds client/TienSkillMastery_SkillsTab.lua from vanilla's ISCharacterInfo:render (42.21) plus our insertions.

    py scripts/make_skills_tab.py

Re-run after a game update changes ISCharacterInfo.lua; each patch asserts its anchor still exists.
"""
import os

GAME = "C:/Program Files (x86)/Steam/steamapps/common/ProjectZomboid/media/lua/client/XpSystem/ISUI/ISCharacterInfo.lua"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "Contents", "mods", "TienSkillMastery", "42", "media", "lua", "client",
                   "TienSkillMastery_SkillsTab.lua")

HEADER = '''--[[
Tien's Skill Mastery: click a skill's name in the vanilla Skills tab to list what its current level gives in vanilla
(registry: shared/TienSkillMastery_SkillEffects*.lua). Click again to close. Joypad: Y on a skill.
Right-click a skill's name for the admin skill cheat menu: add / remove XP, set the level (TienSkillMastery_Panel.lua).

How (42.21, client/XpSystem/ISUI/ISCharacterInfo.lua): `ISCharacterInfo:render` lays the rows out itself and creates
the skill bars (ISSkillProgressBar children) at their row's y only when `progressBarLoaded` is false; collapsing a
category sets `reloadSkillBar`, which removes the bars and builds them again at the new rows. The lines have to sit
between rows, so `render` below is vanilla's, generated by scripts/make_skills_tab.py with three insertions (marked
"Tien's Skill Mastery"): a hint line on top, the width fitted to the content (vanilla only grows it), note each skill row, draw the open skill's lines after its row, and widen the panel for
them. Opening, closing or a change in the number of lines sets `reloadSkillBar` like a collapse does. Long lines wrap
at the mod option's length (`M.wrapText`, TienSkillMastery_Options.lua), the rest indented; a wrapped line counts 1000
in that number, since it is shorter than a row (a change in either moves the bars). A click on the name area reaches `onMouseDown` (the bar is a child and takes clicks over itself first); `y` arrives in content
coordinates (`UIElement.onMouseDown` passes y - yScroll). The joypad Y button does nothing in vanilla.
Another mod replacing `ISCharacterInfo.render` after this file wins over it (and the other way round).
]]

require "XpSystem/ISUI/ISCharacterInfo"
require "TienSkillMastery_SkillEffects"
local M = TienSkillMastery

local UI_BORDER_SPACING = 10;
local FONT_HGT_SMALL = getTextManager():getFontHeight(UIFont.Small)
local BUTTON_HGT = FONT_HGT_SMALL + 6
local SCROLL_BAR_WIDTH = 13

'''

FOOTER = '''

-- ---------------------------------------------------------------------------------------------------------------
-- Tien's Skill Mastery: clicks and joypad
-- ---------------------------------------------------------------------------------------------------------------

local function toggle(self, perk)
    self.tsmOpen = self.tsmOpen or {}
    local id = perk:getId()
    self.tsmOpen[id] = not self.tsmOpen[id] or nil
    self.reloadSkillBar = true
    getSoundManager():playUISound("UIActivateButton")
end

local originalMouseDown = ISCharacterInfo.onMouseDown
function ISCharacterInfo:onMouseDown(x, y)
    for _, r in ipairs(self.tsmRows or {}) do
        if y >= r.y and y < r.y + r.h and x < r.barX then
            toggle(self, r.perk)
            return true
        end
    end
    if originalMouseDown then return originalMouseDown(self, x, y) end
end

-- Right-click a skill's name: the admin skill cheat menu, real XP and level (client/TienSkillMastery_Panel.lua
-- M.showSkillCheatMenu; shown only to roles with AddXP in MP, or with -debug in single player). ISUIElement's empty onRightMouseUp
-- consumed the click before, so nothing vanilla is lost.
local originalRightMouseUp = ISCharacterInfo.onRightMouseUp
function ISCharacterInfo:onRightMouseUp(x, y)
    for _, r in ipairs(self.tsmRows or {}) do
        if y >= r.y and y < r.y + r.h and x < r.barX then
            if M.showSkillCheatMenu then M.showSkillCheatMenu(self.playerNum, r.perk:getId()) end
            return true
        end
    end
    if originalRightMouseUp then return originalRightMouseUp(self, x, y) end
end

local originalJoypadDown = ISCharacterInfo.onJoypadDown
function ISCharacterInfo:onJoypadDown(button)
    if button == Joypad.YButton and self.joypadIndex and self.progressBars[self.joypadIndex] then
        toggle(self, self.progressBars[self.joypadIndex].perk)
        return
    end
    return originalJoypadDown(self, button)
end
'''


def main():
    src = open(GAME, encoding="utf-8").read().replace("\r\n", "\n").split("\n")
    start = next(i for i, l in enumerate(src) if l.startswith("function ISCharacterInfo:render()"))
    end = next(i for i in range(start, len(src)) if src[i] == "end")
    body = "\n".join(src[start:end + 1])

    def patch(old, new):
        nonlocal body
        assert body.count(old) == 1, old
        body = body.replace(old, new)

    patch("function ISCharacterInfo:render()\n\tlocal y = UI_BORDER_SPACING\n",
          "function ISCharacterInfo:render()\n\tlocal y = UI_BORDER_SPACING\n"
          "\t-- Tien's Skill Mastery: rows for clicks, line count to rebuild the bars when it changes, widest line\n"
          "\tself.tsmRows = {}\n\tlocal tsmCount, tsmRight = 0, 0\n"
          "\tlocal tsmPlayer = getSpecificPlayer(self.playerNum)\n"
          "\t-- Tien's Skill Mastery: the hint line above the skills\n"
          "\tfor i, part in ipairs(M.wrapText(getText(\"IGUI_TienSkillMastery_SkillsIntro\"))) do\n"
          "\t\tlocal px = UI_BORDER_SPACING + (i > 1 and M.WRAP_INDENT or 0)\n"
          "\t\tself:drawText(part, px, y, 0.8, 0.8, 0.8, 1, UIFont.Small)\n"
          "\t\ttsmRight = math.max(tsmRight, px + getTextManager():MeasureStringX(UIFont.Small, part))\n"
          "\t\ty = y + FONT_HGT_SMALL\n"
          "\t\tif i > 1 then tsmCount = tsmCount + 1000 end\n"
          "\tend\n"
          "\ty = y + UI_BORDER_SPACING\n")
    patch("\t\t\t\ty = y + rowHgt;\n",
          "\t\t\t\t-- Tien's Skill Mastery: note the row, then the open skill's lines\n"
          "\t\t\t\ttable.insert(self.tsmRows, { y = y, h = rowHgt, perk = perk,\n"
          "\t\t\t\t\tbarX = left + UI_BORDER_SPACING*3 + self.txtLen })\n"
          "\t\t\t\tif self:getMouseY() >= y and self:getMouseY() < y + rowHgt and self:getMouseX() < left + UI_BORDER_SPACING*3 + self.txtLen then\n"
          "\t\t\t\t\tself:drawRect(left, y, self.txtLen + UI_BORDER_SPACING*3, rowHgt, 0.08, 1, 1, 1)\n"
          "\t\t\t\tend\n"
          "\t\t\t\ty = y + rowHgt;\n"
          "\t\t\t\tif self.tsmOpen and self.tsmOpen[perk:getId()] and tsmPlayer then\n"
          "\t\t\t\t\tlocal lines = M.skillEffectLines(perk:getId(), tsmPlayer:getPerkLevel(perk), tsmPlayer)\n"
          "\t\t\t\t\tif #lines == 0 then\n"
          "\t\t\t\t\t\tlines = { { text = getText(\"IGUI_TienSkillMastery_NoEffects\"), gained = false } }\n"
          "\t\t\t\t\tend\n"
          "\t\t\t\t\tfor _, line in ipairs(lines) do\n"
          "\t\t\t\t\t\tlocal c = line.gained and 0.85 or 0.5\n"
          "\t\t\t\t\t\tlocal parts = M.wrapText(line.text)\n"
          "\t\t\t\t\t\tfor i, part in ipairs(parts) do\n"
          "\t\t\t\t\t\t\tlocal lx = left + UI_BORDER_SPACING*4 + (i > 1 and M.WRAP_INDENT or 0)\n"
          "\t\t\t\t\t\t\tself:drawText(part, lx, y+fontOffset, c, c, c, 1, UIFont.Small)\n"
          "\t\t\t\t\t\t\ttsmRight = math.max(tsmRight, lx + getTextManager():MeasureStringX(UIFont.Small, part))\n"
          "\t\t\t\t\t\t\ty = y + (i < #parts and FONT_HGT_SMALL or rowHgt)\n"
          "\t\t\t\t\t\t\tif i > 1 then tsmCount = tsmCount + 1000 end\n"
          "\t\t\t\t\t\tend\n"
          "\t\t\t\t\t\ttsmCount = tsmCount + 1\n"
          "\t\t\t\t\tend\n"
          "\t\t\t\tend\n")
    patch("\tself:setWidthAndParentWidth(math.max(self.width, ",
          "\t-- Tien's Skill Mastery: rebuild the bars when the number of lines changed (a level gained or lost)\n"
          "\tif self.progressBarLoaded and self.tsmLastCount ~= nil and self.tsmLastCount ~= tsmCount then\n"
          "\t\tself.reloadSkillBar = true\n\tend\n\tself.tsmLastCount = tsmCount\n"
          "\t-- Tien's Skill Mastery: fit the content (vanilla only grows: math.max(self.width, ...)), never below the\n"
          "\t-- width the view was made with (the tab strip's)\n"
          "\tself.tsmMinWidth = self.tsmMinWidth or self.width\n"
          "\tself:setWidthAndParentWidth(math.max(self.tsmMinWidth, tsmRight + UI_BORDER_SPACING + SCROLL_BAR_WIDTH, ")

    text = HEADER + body + FOOTER
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
