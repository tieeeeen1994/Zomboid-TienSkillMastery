--[[
Tien's Skill Mastery: click a skill's name in the vanilla Skills tab to list what its current level gives in vanilla
(registry: shared/TienSkillMastery_SkillEffects*.lua). Click again to close. Joypad: Y on a skill.
Right-click a skill's name for the admin skill cheat menu: add / remove XP, set the level (TienSkillMastery_Panel.lua).

How (42.21, client/XpSystem/ISUI/ISCharacterInfo.lua): `ISCharacterInfo:render` lays the rows out itself and creates
the skill bars (ISSkillProgressBar children) at their row's y only when `progressBarLoaded` is false; collapsing a
category sets `reloadSkillBar`, which removes the bars and builds them again at the new rows. The lines have to sit
between rows, so `render` below is vanilla's, generated by scripts/make_skills_tab.py with three insertions (marked
"Tien's Skill Mastery"): a hint line on top, the width fitted to the content (vanilla only grows it), note each skill row, draw the open skill's lines after its row, and widen the panel for
them. Opening, closing or a change in the number of lines sets `reloadSkillBar` like a collapse does. Long lines wrap
at the mod option's length (`M.wrapText`, TienSkillMastery_Options.lua), the rest indented; a wrapped line counts 1000
in that number, since it is shorter than a row (a change in either moves the bars). A click on the name area reaches `onMouseDown` (the bar is a child and takes clicks over itself first); `y` arrives in content
coordinates (`UIElement.onMouseDown` passes y - yScroll). The joypad Y button does nothing in vanilla.
Another mod replacing `ISCharacterInfo.render` after this file wins over it (and the other way round).
]]

require "XpSystem/ISUI/ISCharacterInfo"
require "TienSkillMastery_SkillEffects"
local M = TienSkillMastery

local UI_BORDER_SPACING = 10;
local FONT_HGT_SMALL = getTextManager():getFontHeight(UIFont.Small)
local BUTTON_HGT = FONT_HGT_SMALL + 6
local SCROLL_BAR_WIDTH = 13

function ISCharacterInfo:render()
	local y = UI_BORDER_SPACING
	-- Tien's Skill Mastery: rows for clicks, line count to rebuild the bars when it changes, widest line
	self.tsmRows = {}
	local tsmCount, tsmRight = 0, 0
	local tsmPlayer = getSpecificPlayer(self.playerNum)
	-- Tien's Skill Mastery: the hint line above the skills
	for i, part in ipairs(M.wrapText(getText("IGUI_TienSkillMastery_SkillsIntro"))) do
		local px = UI_BORDER_SPACING + (i > 1 and M.WRAP_INDENT or 0)
		self:drawText(part, px, y, 0.8, 0.8, 0.8, 1, UIFont.Small)
		tsmRight = math.max(tsmRight, px + getTextManager():MeasureStringX(UIFont.Small, part))
		y = y + FONT_HGT_SMALL
		if i > 1 then tsmCount = tsmCount + 1000 end
	end
	y = y + UI_BORDER_SPACING

	if self.lastLevelUpTime > 0 then
		self.lastLevelUpTime = self.lastLevelUpTime - 0.0025
	elseif self.lastLevelUpTime < 0 then
		self.lastLevelUpTime = 0
	end

	ISSkillProgressBar.updateAlpha() -- FIXME: do this once per frame, not for each player
	-- how much skills pts we got ?
	if self.reloadSkillBar then
		self.progressBarLoaded = false;
		self.reloadSkillBar = false;
		for i,v in pairs(self.progressBars) do
			self:removeChild(v);
		end
		self.progressBars = {}

	end

	local top = y

	-- if we got a multiplier, we gonna anim that with ">, >>, >>>"
	 -- FIXME: do this once per frame, not for each player
	local ms = UIManager.getMillisSinceLastRender()
	ISCharacterInfo.timerMultiplierAnim = ISCharacterInfo.timerMultiplierAnim + ms;
	if ISCharacterInfo.timerMultiplierAnim <= 500 then
        ISCharacterInfo.animOffset = -1;
	elseif ISCharacterInfo.timerMultiplierAnim <= 1000 then
        ISCharacterInfo.animOffset = 0;
	elseif ISCharacterInfo.timerMultiplierAnim <= 1500 then
        ISCharacterInfo.animOffset = 15;
	elseif ISCharacterInfo.timerMultiplierAnim <= 2000 then
        ISCharacterInfo.animOffset = 30;
	else
		ISCharacterInfo.timerMultiplierAnim = 0;
	end

	local left = UI_BORDER_SPACING*2+BUTTON_HGT+1
	local maxY = y
	local fontOffset = (BUTTON_HGT-FONT_HGT_SMALL)/2
	local rowHgt = BUTTON_HGT
	for i,parentPerk in ipairs(self.sorted) do
		local perkList = self.perks[parentPerk:getType()]
		-- we first draw our parent name
		self:drawText(parentPerk:getName(), left, y+fontOffset, 1, 1, 1, 1, UIFont.Small);
		self.buttonList[i]:setY(y)
		y = y + math.max(BUTTON_HGT);
		-- then all the skills with their progress bar
		if not self.collapse[i] then
			self:drawTexture(self.SkillBarSeparator, 0, y + UI_BORDER_SPACING, 1,1,1,1);
			y = y + UI_BORDER_SPACING
			for ind, perk in ipairs(perkList) do
				local xpBoost = self.char:getXp():getPerkBoost(perk:getType());
				local r = 1;
				local g = 1;
				local b = 1;
				if xpBoost == 0 then
					r = 0.54;
					g = 0.54;
					b = 0.54;
				elseif xpBoost == 1 then
					r = 0.8;
					g = 0.8;
					b = 0.8;
				elseif xpBoost == 3 then
					r = 1;
					g = 0.83;
					b = 0;
				end
				self:drawText(perk:getName(), left + UI_BORDER_SPACING*2, y+fontOffset, r, g, b, 1, UIFont.Small);
				--todo add tooltips to the skill titles
				-- if we got a multiplier, we gonna anim that with ">, >>, >>>"
				if self.char:getXp():getMultiplier(perk:getType()) > 0 then
					--for some reason, the experience boost arrows are offset in X and Y by +2 pixels. I have no explanation why. ~Fox
					local arrowPixelOffset = 2

					local arrowHeight = self.arrow:getHeight()
					local arrowOffset = math.floor((BUTTON_HGT-arrowHeight)/2)-arrowPixelOffset
					self:drawTexture(self.disabledArrow, UI_BORDER_SPACING+1-arrowPixelOffset, y+arrowOffset, 1, 1, 1, 1);
					self:drawTexture(self.disabledArrow, UI_BORDER_SPACING+1+15-arrowPixelOffset, y+arrowOffset, 1, 1, 1, 1);
					self:drawTexture(self.disabledArrow, UI_BORDER_SPACING+1+30-arrowPixelOffset, y+arrowOffset, 1, 1, 1, 1);

					if ISCharacterInfo.animOffset > -1 then
						self:drawTexture(self.arrow, UI_BORDER_SPACING+1 + ISCharacterInfo.animOffset - arrowPixelOffset, y+arrowOffset, 1, 1, 1, 1);
					end
				end
				if not self.progressBarLoaded then
					local skillPointSize = math.floor((FONT_HGT_SMALL + 6)/2)
					local skillPointOffset = (BUTTON_HGT-skillPointSize)/2
					local progressBar = ISSkillProgressBar:new(left + UI_BORDER_SPACING*3 + self.txtLen, y+skillPointOffset, 0, 0, self.playerNum, perk, self);
					progressBar:initialise();

					self:addChild(progressBar);
					table.insert(self.progressBars, progressBar);
				end
				-- Tien's Skill Mastery: note the row, then the open skill's lines
				table.insert(self.tsmRows, { y = y, h = rowHgt, perk = perk,
					barX = left + UI_BORDER_SPACING*3 + self.txtLen })
				if self:getMouseY() >= y and self:getMouseY() < y + rowHgt and self:getMouseX() < left + UI_BORDER_SPACING*3 + self.txtLen then
					self:drawRect(left, y, self.txtLen + UI_BORDER_SPACING*3, rowHgt, 0.08, 1, 1, 1)
				end
				y = y + rowHgt;
				if self.tsmOpen and self.tsmOpen[perk:getId()] and tsmPlayer then
					local lines = M.skillEffectLines(perk:getId(), tsmPlayer:getPerkLevel(perk), tsmPlayer)
					if #lines == 0 then
						lines = { { text = getText("IGUI_TienSkillMastery_NoEffects"), gained = false } }
					end
					for _, line in ipairs(lines) do
						local c = line.gained and 0.85 or 0.5
						local parts = M.wrapText(line.text)
						for i, part in ipairs(parts) do
							local lx = left + UI_BORDER_SPACING*4 + (i > 1 and M.WRAP_INDENT or 0)
							self:drawText(part, lx, y+fontOffset, c, c, c, 1, UIFont.Small)
							tsmRight = math.max(tsmRight, lx + getTextManager():MeasureStringX(UIFont.Small, part))
							y = y + (i < #parts and FONT_HGT_SMALL or rowHgt)
							if i > 1 then tsmCount = tsmCount + 1000 end
						end
						tsmCount = tsmCount + 1
					end
				end
			end
		end
		y = y + UI_BORDER_SPACING;
		maxY = math.max(maxY, y)
	end
	y = y + 1;

	local skillPointSize = math.floor((FONT_HGT_SMALL + 6)/2)
	local skillPointSpacing = getCore():getOptionFontSizeReal()

	-- Tien's Skill Mastery: rebuild the bars when the number of lines changed (a level gained or lost)
	if self.progressBarLoaded and self.tsmLastCount ~= nil and self.tsmLastCount ~= tsmCount then
		self.reloadSkillBar = true
	end
	self.tsmLastCount = tsmCount
	-- Tien's Skill Mastery: fit the content (vanilla only grows: math.max(self.width, ...)), never below the
	-- width the view was made with (the tab strip's)
	self.tsmMinWidth = self.tsmMinWidth or self.width
	self:setWidthAndParentWidth(math.max(self.tsmMinWidth, tsmRight + UI_BORDER_SPACING + SCROLL_BAR_WIDTH, left + UI_BORDER_SPACING*4 + self.txtLen + skillPointSize*10 + skillPointSpacing*9 + SCROLL_BAR_WIDTH + 1));
	self:setHeightAndParentHeight(math.min(y, 800));

	self:setScrollHeight(y)

	self.progressBarLoaded = true;

	if self.joyfocus then
		if self.joypadIndex and self.joypadIndex >= 1 and self.joypadIndex <= #self.progressBars then
			local bar = self.progressBars[self.joypadIndex]
			local left = bar:getX() - (self.txtLen + 45)
			local right = bar:getX() + bar:getWidth()
			self:drawRectBorder(left-2, bar:getY()-2, (right - left) + 2, bar:getHeight() + 3, 0.4, 0.2, 1.0, 1.0);
			if bar.tooltip then
				bar.tooltip.followMouse = false
				bar.tooltip:setX(bar:getAbsoluteX())
				local tty = bar:getAbsoluteY() + bar:getHeight() + 1
				if tty + bar.tooltip:getHeight() > getCore():getScreenHeight() then
					tty = bar:getAbsoluteY() - bar.tooltip:getHeight() - 1
				end
				bar.tooltip:setY(tty)
			end
		end
	end

	self:clearStencilRect()
end

-- ---------------------------------------------------------------------------------------------------------------
-- Tien's Skill Mastery: clicks and joypad
-- ---------------------------------------------------------------------------------------------------------------

local function toggle(self, perk)
    self.tsmOpen = self.tsmOpen or {}
    local id = perk:getId()
    self.tsmOpen[id] = not self.tsmOpen[id] or nil
    self.reloadSkillBar = true
    getSoundManager():playUISound("UIActivateButton")
end

local originalMouseDown = ISCharacterInfo.onMouseDown
function ISCharacterInfo:onMouseDown(x, y)
    for _, r in ipairs(self.tsmRows or {}) do
        if y >= r.y and y < r.y + r.h and x < r.barX then
            toggle(self, r.perk)
            return true
        end
    end
    if originalMouseDown then return originalMouseDown(self, x, y) end
end

-- Right-click a skill's name: the admin skill cheat menu, real XP and level (client/TienSkillMastery_Panel.lua
-- M.showSkillCheatMenu; shown only to roles with AddXP in MP, or with -debug in single player). ISUIElement's empty onRightMouseUp
-- consumed the click before, so nothing vanilla is lost.
local originalRightMouseUp = ISCharacterInfo.onRightMouseUp
function ISCharacterInfo:onRightMouseUp(x, y)
    for _, r in ipairs(self.tsmRows or {}) do
        if y >= r.y and y < r.y + r.h and x < r.barX then
            if M.showSkillCheatMenu then M.showSkillCheatMenu(self.playerNum, r.perk:getId()) end
            return true
        end
    end
    if originalRightMouseUp then return originalRightMouseUp(self, x, y) end
end

local originalJoypadDown = ISCharacterInfo.onJoypadDown
function ISCharacterInfo:onJoypadDown(button)
    if button == Joypad.YButton and self.joypadIndex and self.progressBars[self.joypadIndex] then
        toggle(self, self.progressBars[self.joypadIndex].perk)
        return
    end
    return originalJoypadDown(self, button)
end
